function [J3, J_at] = build_emm_j3(T, J1, tool)
%BUILD_EMM_J3 无量纲误差映射矩阵 J3（c13 式(52)~(55)）
%   以 3 个靶球特征点（不共线）的位置误差等效表达末端全位姿误差，同时
%   引入辅助测量工具的尺寸误差，使 EMM 各项无量纲：
%       Δ3 = [Δm1; Δm2; Δm3] = J3·ε3
%       ε3 = [ε(35); Δc(3)]  （38 个误差参数，全部为长度量纲）
%       J3 = J_at · [J1, 0(6×3); 0(3×35), I3]   (9×38)
%
%   特征点与位姿的关系（文献式(51)）：
%       m_i = o + R·(o0 + R0·c_i),  i = 1..3
%   其中 {at} 为工具坐标系（原点位于特征点 C1，x 轴过 C2，C3 在 xy 平面
%   内），eeT_at = [R0, o0] 为 {at}→{ee} 的固定齐次变换。按 {at} 的建立
%   方式：
%       c_1 = [0;0;0],  c_2 = [c1;0;0],  c_3 = [c2;c3;0]
%   （c 各分量允许为负，等价于 {at} 绕 z 轴转 180° 的取向。）
%   本项目中测量靶球与文献特征点的对应关系为 C1=t2, C2=t3, C3=t1，
%   由 calibration6_c13_exp.m 在装配测量数据时完成列重排。
%   辅助工具误差参数 Δc = [Δc1; Δc2; Δc3]。
%
%   J_at（文献式(53)）各行：
%     Δm1 = Δo - [R·o0×]Δθ
%     Δm2 = Δo - [R(o0 + c1·R0·e1)×]Δθ + Δc1·R·R0·e1
%     Δm3 = Δo - [R(o0 + c2·R0·e1 + c3·R0·e2)×]Δθ + Δc2·R·R0·e1 + Δc3·R·R0·e2
%
%   输入：
%     T    — 4×4 当前动平台位姿（FKS 计算值）
%     J1   — 6×35 传统 EMM（build_emm_j1_spr4ups 的输出）
%     tool — 辅助工具结构体：
%              .o0  3×1 {at} 原点在 {ee} 中的坐标
%              .R0  3×3 {at} 相对 {ee} 的姿态矩阵
%              .c   3×1 工具名义尺寸 [c1; c2; c3]
%   输出：
%     J3   — 9×38 无量纲 EMM
%     J_at — 9×9 位姿误差→特征点误差映射阵

    R = T(1:3, 1:3);
    o0 = tool.o0;
    R0 = tool.R0;
    c = tool.c(:);
    e1 = [1; 0; 0];
    e2 = [0; 1; 0];

    z31 = zeros(3, 1);
    RR0e1 = R * R0 * e1;
    RR0e2 = R * R0 * e2;

    J_at = [eye(3), -skew(R*o0),                                z31,   z31,   z31;
            eye(3), -skew(R*(o0 + c(1)*R0*e1)),                 RR0e1, z31,   z31;
            eye(3), -skew(R*(o0 + c(2)*R0*e1 + c(3)*R0*e2)),    z31,   RR0e1, RR0e2];

    J3 = J_at * [J1, zeros(6, 3); zeros(3, 35), eye(3)];
end
